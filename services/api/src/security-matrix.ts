import type { AdminRouteDefinition } from './platform/http/admin-routes.js';
import type { RouteDefinition } from './platform/http/routes.js';
import type { RateLimitPolicy } from './platform/rate-limit.js';

/**
 * The route security matrix (docs/security/route-matrix.md): for every user-API and admin route,
 * who may call it, under which policy, with which rate limit, and what it audits. Generated from
 * the route definitions (cli/security-matrix.ts), so the review document cannot drift from the
 * code; CI regenerates it and fails on a difference, as for the OpenAPI document. The invariants
 * the security review relies on are checked in security-matrix.test.ts.
 */
export function renderMatrix(
  routes: readonly RouteDefinition[],
  adminRoutes: readonly AdminRouteDefinition[],
): string {
  const lines = [
    '# Route security matrix',
    '',
    'Generated by `pnpm --filter @tessera/api security-matrix` from the route definitions — do not',
    'edit. Columns: authentication (`session` stages, step-up), authorization policy, rate limit',
    '(requests per period, burst, behaviour when the shared limiter store is down), audit.',
    '',
    `## User API (${String(routes.length)} routes)`,
    '',
    '| Route | Method | Path | Auth | Policy | Rate limit | Audit |',
    '|---|---|---|---|---|---|---|',
    ...[...routes]
      .sort((a, b) => a.id.localeCompare(b.id))
      .map((route) =>
        row([
          route.id,
          route.method,
          route.url,
          userAuth(route.auth),
          route.authorize.name,
          limit(route.rateLimit),
          route.audit.kind === 'records'
            ? `records ${route.audit.actions.join(', ')}`
            : `none — ${route.audit.reason}`,
        ]),
      ),
    '',
    `## Admin API (${String(adminRoutes.length)} routes; every call is audited)`,
    '',
    '| Route | Method | Path | Auth | Capability | Rate limit |',
    '|---|---|---|---|---|---|',
    ...[...adminRoutes]
      .sort((a, b) => a.id.localeCompare(b.id))
      .map((route) =>
        row([
          route.id,
          route.method,
          route.url,
          route.auth.kind === 'public'
            ? 'public'
            : `session${route.auth.stages === undefined ? '' : ` (${route.auth.stages.join('/')})`}${route.auth.stepUp === true ? ', step-up' : ''}`,
          route.auth.kind === 'session' ? (route.auth.capability ?? '—') : '—',
          limit(route.rateLimit),
        ]),
      ),
    '',
  ];
  return lines.join('\n');
}

function userAuth(auth: RouteDefinition['auth']): string {
  if (auth.kind !== 'session') return auth.kind;
  const stages = auth.stages === undefined ? '' : ` (${auth.stages.join('/')})`;
  const stepUp =
    auth.stepUp === true
      ? ', step-up'
      : auth.stepUp === 'when-active'
        ? ', step-up when active'
        : '';
  return `session${stages}${stepUp}`;
}

function limit(policy: RateLimitPolicy): string {
  const period =
    policy.periodMs % 3_600_000 === 0
      ? `${String(policy.periodMs / 3_600_000)} h`
      : policy.periodMs % 60_000 === 0
        ? `${String(policy.periodMs / 60_000)} min`
        : `${String(policy.periodMs / 1000)} s`;
  return `${String(policy.limit)}/${period} (burst ${String(policy.burst)}, fails ${policy.onStoreFailure})`;
}

function row(cells: readonly string[]): string {
  return `| ${cells.map((cell) => cell.replaceAll('|', '\\|')).join(' | ')} |`;
}
