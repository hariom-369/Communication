import { stringify } from 'yaml';

import { manifests, type Manifest } from './manifests.js';
import type { Values } from './values.js';

/** Kinds applied in the second phase, after the migration Job has completed. */
const WORKLOADS = new Set(['Deployment', 'HorizontalPodAutoscaler', 'PodDisruptionBudget']);
const FIRST = ['Namespace', 'ServiceAccount', 'ConfigMap', 'ExternalSecret', 'Certificate'];

export interface Rendered {
  /** Namespaces, identities, settings, secrets, network policy, services, routing, monitoring
   * and the release's migration Job. */
  readonly prepare: string;
  /** Deployments, their autoscalers and disruption budgets. */
  readonly workloads: string;
}

function documents(values: Values, list: Manifest[], phase: string): string {
  const rank = (m: Manifest) => {
    const index = FIRST.indexOf(m.kind);
    return index === -1 ? FIRST.length : index;
  };
  const sorted = list
    .map((manifest, index) => ({ manifest, index }))
    .sort((a, b) => rank(a.manifest) - rank(b.manifest) || a.index - b.index)
    .map(({ manifest }) => manifest);
  const header = [
    `# Generated by infra/k8s for ${values.environment}, release ${values.release} (${phase}).`,
    '# Do not edit: change infra/k8s/src/manifests.ts and render again.',
  ].join('\n');
  return `${header}\n${sorted.map((m) => `---\n${stringify(m, { lineWidth: 0 })}`).join('')}`;
}

/** The environment in two files, applied in order (ops/runbooks/deploy-rollback.md). */
export function render(values: Values): Rendered {
  const all = manifests(values);
  return {
    prepare: documents(
      values,
      all.filter((m) => !WORKLOADS.has(m.kind)),
      '1 of 2: prepare',
    ),
    workloads: documents(
      values,
      all.filter((m) => WORKLOADS.has(m.kind)),
      '2 of 2: workloads',
    ),
  };
}
